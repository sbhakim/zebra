"""Characterise each rule over the corpus before any learning.

This diagnostic helped formulate the rules, so it is exploratory rather than
confirmatory -- association over the released corpus, not protocol coverage.
Scored on raw windows (ADR-001). Confirming the rules generalise needs a corpus
they were not developed on.
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score

from zebra.data.corpus import discover_domains, raw_windows
from zebra.invariants.registry import ORDER, violation_scores

ROOT = Path(__file__).resolve().parents[3] / "corpus/IoT-Attacks-IDS/src/attack_data"
OUT = Path(__file__).resolve().parents[3] / "generated"
MACRO = "ZBInv"
# A descriptive reference line, not a coverage or significance threshold.
REFERENCE_AUC = 0.70


@dataclass(frozen=True, slots=True)
class AttackProbe:
    """One attack's standalone AUC against every rule.

    A record rather than a dict: this row reaches the manuscript, and the whole
    package's rule is that anything crossing a boundary is typed (model.py).
    """

    attack: str
    r1_solicitation: float
    r2_regularity: float
    r3_dispersion: float
    best: str
    best_auc: float
    above_reference: bool


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    per: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))

    for ident in discover_domains(ROOT):
        x, y = raw_windows(ROOT, ident)
        if len(np.unique(y)) < 2:
            raise ValueError(f"{ident.name}: single-class domain, cannot score AUC")
        nu = violation_scores(x)
        for k, inv in enumerate(ORDER):
            per[ident.attack.value][inv.value].append(float(roc_auc_score(y, nu[:, k])))

    rows: list[AttackProbe] = []
    for attack in sorted(per):
        aucs = {i: float(np.mean(per[attack][i.value])) for i in ORDER}
        best = max(ORDER, key=lambda i: aucs[i])
        rows.append(
            AttackProbe(
                attack=attack,
                r1_solicitation=round(aucs[ORDER[0]], 3),
                r2_regularity=round(aucs[ORDER[1]], 3),
                r3_dispersion=round(aucs[ORDER[2]], 3),
                best=best.value,
                best_auc=round(aucs[best], 3),
                above_reference=aucs[best] >= REFERENCE_AUC,
            )
        )

    dicts = [asdict(r) for r in rows]
    (OUT / "rule_probe.json").write_text(json.dumps(dicts, indent=1))
    with (OUT / "rule_probe.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(dicts[0]))
        writer.writeheader()
        writer.writerows(dicts)

    lines = ["% Exploratory diagnostic generated by zebra.eval.probe; do not edit."]
    for r in rows:
        tag = r.attack.capitalize()
        lines.append(rf"\def\{MACRO}{tag}BestAUC{{{r.best_auc:.3f}}}")
        lines.append(
            rf"\def\{MACRO}{tag}AboveReference"
            rf"{{{'yes' if r.above_reference else 'no'}}}"
        )
    above = [r.attack for r in rows if r.above_reference]
    lines.append(rf"\def\{MACRO}NumAboveReference{{{len(above)}}}")
    lines.append(rf"\def\{MACRO}ReferenceAUC{{{REFERENCE_AUC:.2f}}}")
    (OUT / "rule_probe.tex").write_text("\n".join(lines) + "\n")

    col = max(len(i.value) for i in ORDER) + 2
    head = "".join(f"{i.value:>{col}}" for i in ORDER)
    print(f"{'attack':<16}{head}{'best':>10}{'above':>9}")
    print("-" * (16 + col * len(ORDER) + 19))
    for r in rows:
        cells = "".join(
            f"{v:>{col}.3f}"
            for v in (r.r1_solicitation, r.r2_regularity, r.r3_dispersion)
        )
        flag = "yes" if r.above_reference else "NO"
        print(f"{r.attack:<16}{cells}{r.best_auc:>10.3f}{flag:>9}")
    print(f"\nabove descriptive AUC {REFERENCE_AUC}: {len(above)}/5 -- {', '.join(above)}")
    print(f"wrote {OUT}/rule_probe.{{json,csv}} and rule_probe.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
