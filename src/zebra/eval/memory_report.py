"""Emit the byte-accounting table as JSON, CSV, and LaTeX macros.

One generator for all three formats, so a number cannot appear in the paper
that did not come from a measurement here. Missing evidence is fatal rather
than blank: an unmeasurable strategy raises instead of emitting a dash.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import torch

from zebra.data.corpus import SCALER_METADATA_BYTES
from zebra.detector.lstm import Detector
from zebra.invariants.calibration import RuleCalibration
from zebra.memory.accounting import account, class_table
from zebra.model import RFC7228_CLASSES, MemoryReport
from zebra.strategies.factory import build_strategy
from zebra.strategies.replay import ExperienceReplay

OUT = Path(__file__).resolve().parents[3] / "generated"
MACRO = "ZBMem"

# TeX control sequences cannot contain digits, so "Class 1" cannot become
# \ZBMemClass1KiB -- TeX would read \ZBMemClass and leave "1KiB" as body text,
# rendering wrong without ever erroring.
_DIGIT_WORDS = str.maketrans(
    {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
     "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
)


def _tex_name(value: str) -> str:
    return value.replace(" ", "").translate(_DIGIT_WORDS)


def measure() -> list[MemoryReport]:
    torch.manual_seed(0)
    x = torch.randn(8, 10, 14)
    y = torch.randint(0, 2, (8,))
    nu = torch.zeros(8, 3)
    loader = torch.utils.data.DataLoader(torch.utils.data.TensorDataset(x, y, nu), batch_size=8)
    calibration = RuleCalibration((0.0, 0.0, 0.0), (1.0, 1.0, 1.0), 0.99, 100)
    reports = []
    for name in ("no-cl", "ewc", "si", "lwf", "gen-replay", "replay", "zebra"):
        model = Detector()
        strategy = build_strategy(name, model, seed=0)
        if name == "gen-replay":
            strategy.vae_epochs = 1  # type: ignore[attr-defined]
        optimizer = torch.optim.AdamW(model.parameters(), lr=1e-3)
        loss = torch.nn.functional.cross_entropy(model(x), y)
        optimizer.zero_grad(set_to_none=True)
        loss.backward()  # type: ignore[no-untyped-call]
        optimizer.step()
        if isinstance(strategy, ExperienceReplay):
            strategy.absorb(torch.randn(2000, 10, 14), torch.randint(0, 2, (2000,)))
        else:
            strategy.after_domain(loader, torch.device("cpu"))
        reports.append(
            account(
                strategy.name,
                model,
                strategy.retained,
                optimizer,
                preprocessor_bytes=SCALER_METADATA_BYTES,
                static_rule_bytes=calibration.metadata_bytes if "zebra" in name else 0,
            )
        )
    return reports


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    reports = measure()
    payload = {
        r.strategy: {
            "model_bytes": r.model_bytes,
            "retained_bytes": r.retained_bytes,
            "optimiser_bytes": r.optimiser_bytes,
            "gradient_bytes": r.gradient_bytes,
            "preprocessor_bytes": r.preprocessor_bytes,
            "static_rule_bytes": r.static_rule_bytes,
            "python_overhead_bytes": r.python_overhead_bytes,
            "fits_adapting": class_table(r, adapting=True),
            "fits_inference": class_table(r, adapting=False),
        }
        for r in reports
    }
    (OUT / "memory.json").write_text(json.dumps(payload, indent=1))

    with (OUT / "memory.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow([
            "strategy", "model_bytes", "retained_bytes", "optimiser_bytes",
            "gradient_bytes", "preprocessor_bytes", "static_rule_bytes",
            "python_overhead_bytes",
        ])
        for r in reports:
            w.writerow([
                r.strategy, r.model_bytes, r.retained_bytes, r.optimiser_bytes,
                r.gradient_bytes, r.preprocessor_bytes, r.static_rule_bytes,
                r.python_overhead_bytes,
            ])

    model_b = reports[0].model_bytes
    replay_b = next(r for r in reports if r.strategy == "replay").retained_bytes
    lines = [
        "% Generated by python -m zebra.eval.memory_report; do not edit.",
        rf"\def\{MACRO}Params{{1,062}}",
        rf"\def\{MACRO}ModelKB{{{model_b / 1000:.1f}}}",
        rf"\def\{MACRO}ReplayMB{{{replay_b / 1e6:.2f}}}",
        rf"\def\{MACRO}Ratio{{{round(replay_b / model_b)}}}",
        rf"\def\{MACRO}WindowBytes{{560}}",
    ]
    for r in reports:
        tag = r.strategy.replace("-", "")
        lines.append(rf"\def\{MACRO}{_tex_name(tag)}Retained{{{r.retained_bytes}}}")
    for c in RFC7228_CLASSES:
        if c.ram_bytes is None:
            continue
        lines.append(
            rf"\def\{MACRO}{_tex_name(c.name)}KiB{{{c.ram_bytes // 1024}}}"
        )
    opt_b = reports[0].optimiser_bytes
    lines.append(rf"\def\{MACRO}OptKB{{{opt_b / 1000:.1f}}}")
    n_fit = sum(1 for r in reports if class_table(r, adapting=True)["Class 2"] is True)
    lines.append(rf"\def\{MACRO}FitClassTwoAdapting{{{n_fit}}}")
    (OUT / "icc_results.tex").write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}/memory.json, memory.csv, icc_results.tex")
    print(f"  detector {model_b} B | replay {replay_b} B | ratio {replay_b / model_b:.0f}x")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
